/**
 * Pattern-phase node.
 *
 * The gray imagery pattern is presented at block start and
 * every `config.pattern.pattern_phase_frequency_trials` (= 8) trials
 * thereafter, for `config.pattern.pattern_phase_duration_ms` (= 4000 ms).
 * The participant uses these intervals to refresh their mental image of the
 * pattern, which the imagery (star) judgements depend on.
 *
 * Implementation: a single jsPsych html-keyboard-response node that mounts a
 * non-rotated grid frame, builds the 13-cell gray pattern overlay at 33 %
 * opacity, shows it for the configured duration, then ends. The grid frame
 * is identical to the one used during encoding (same SVG / cell layout) so
 * the participant sees the pattern in the same visual frame they will
 * compare stars against.
 *
 * Note: this node is *non-rotated*. The rotation happens at trial onset
 * during the rotation-cue + animation phase of imagery-bearing trials —
 * the pattern phase itself is the "canonical" upright view.
 *
 * The pattern-phase node is NOT generated by per-condition trial generators
 * (memory-block.js, imagery-block.js, dual-block.js); it is injected at the
 * block-assembly level by `assembleBlock` (block.js).
 */
import htmlKeyboardResponse from '@jspsych/plugin-html-keyboard-response';

import { createGridFrame } from '../visuals/frame.js';
import { buildPatternOverlay, showPattern } from '../visuals/pattern.js';
import { config } from '../config.js';
import { stampTrialData } from './shared.js';

const MOUNT_ID = 'pattern-phase-mount';

/**
 * Build the pattern-phase jsPsych node.
 *
 * @param {object} opts
 * @param {string} opts.block_label             arbitrary tag for data records (e.g. 'practice', 'main_a')
 * @param {number} opts.trial_index_in_block    pool index of the trial this phase belongs to (the same value every row of that trial carries)
 * @param {'white'|'gray'|null} [opts.background_shade]
 *                                              Shade of the upcoming trial. The page-flip is already
 *                                              applied by the trial-start gate's `finishGate` step
 *                                              (the gate runs immediately before this node), so the
 *                                              shade is forwarded only to keep the SVG frame
 *                                              palette (pattern fill + bull's-eye/fixation ink) in
 *                                              sync with the participant-visible page background.
 * @returns {object}                            jsPsych trial object
 */
export function patternPhaseNode({ block_label, trial_index_in_block, background_shade } = {}) {
  return {
    type: htmlKeyboardResponse,
    stimulus: `
      <div style="display: grid; place-items: center; gap: 1rem;">
        <div id="${MOUNT_ID}" style="margin: 0 auto;"></div>
      </div>
    `,
    choices: 'NO_KEYS',
    trial_duration: config.pattern.pattern_phase_duration_ms,
    on_load: () => {
      const mount = document.getElementById(MOUNT_ID);
      const frame = createGridFrame({
        rotation_deg: 0,
        fixation: '',
        background_shade,
      });
      mount.appendChild(frame.wrapper);
      buildPatternOverlay(frame);
      showPattern(frame);
      stampTrialData('pattern_onset_ts_ms', performance.now());
    },
    data: {
      phase: 'pattern_phase',
      block_label,
      trial_index_in_block,
      background_shade,
      duration_ms: config.pattern.pattern_phase_duration_ms,
    },
  };
}
